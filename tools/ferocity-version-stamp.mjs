import fs from 'node:fs';import {createHash} from 'node:crypto';
let html=fs.readFileSync('index.html','utf8');
const from="const APP_VERSION='0.4.346'",to="const APP_VERSION='0.4.347'";
if(html.split(from).length!==2)throw Error('Expected exactly one accepted version stamp');
html=html.replace(from,to);
fs.writeFileSync('index.html',html);
const path='validation/manifests/v0.4.347.json',manifest=JSON.parse(fs.readFileSync(path,'utf8'));
if(manifest.version!=='0.4.347'||manifest.core.length<2350)throw Error('Unexpected candidate manifest');
manifest.productionSha256=createHash('sha256').update(html).digest('hex');
fs.writeFileSync(path,JSON.stringify(manifest,null,2)+'\n');
console.log('v0.4.347 production SHA-256 '+manifest.productionSha256);
